from math import cos, pi, sin


def arc(cx, cy, rx, ry, start, end, steps=16):
    return [
        (cx + rx * cos((start + (end - start) * index / steps) * pi / 180),
         cy + ry * sin((start + (end - start) * index / steps) * pi / 180))
        for index in range(steps + 1)
    ]


